/** Все подразделы темы (или undefined, если у темы их нет). */
export const getSubsections = (
  sectionId: string,
  topicSlug: string
): Subsection[] | undefined => SUBSECTIONS[`${sectionId}/${topicSlug}`];

/** Один подраздел по URL-сегментам. */
export const getSubsection = (
  sectionId: string,
  topicSlug: string,
  subSlug: string
): Subsection | undefined =>
  getSubsections(sectionId, topicSlug)?.find((s) => s.slug === subSlug);
